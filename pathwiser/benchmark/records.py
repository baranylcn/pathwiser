"""Model-ready records: the validated benchmark (``data/processed``) turned into what a model consumes (``data/model``).

* text normalisation (Unicode NFC, control characters, whitespace; no lower-casing),
* a bounded conversation context (newest turns kept; the current message is never truncated),
* one rendered ``query`` string plus the candidate descriptions (never condition ids),
* targets (``label`` / ``label_null`` / ``has_match``),
* training weights (dataset balancing and a discount for risky labels; train split only).

Run ``pathwiser benchmark records``. The output is deterministic: the same inputs and options give byte-identical files.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
import unicodedata
from collections import Counter
from dataclasses import asdict, dataclass
from pathlib import Path

from pathwiser.benchmark.fileio import write_text
from pathwiser.benchmark.schema import PipelineError
from pathwiser.storage.hashing import sha256_file

SPLITS = ("train", "val", "test")
SOURCE_JSONL = tuple(f"{s}.jsonl" for s in SPLITS)

SCHEMA_MD = """# Model-ready dataset

Generated by `pathwiser benchmark records` from the benchmark in `data/processed/<version>`.
`manifest.json` records the source hashes and the exact preprocessing options.

One JSON object per line, one line per decision example (**listwise**):

```
example_id            str    stable id (same as in data/processed)
split                 str    train | val | test
input.node            {name, description}
input.context         [{role: user|assistant, content}]   newest turns kept, oldest dropped on budget overflow
input.message         str    current user message (never truncated by the context budget)
input.query           str    rendered node + context + message  (feed this to the model)
input.conditions      [str]  candidate descriptions, k items, order is shuffled; NO condition ids
target.label          int    index of the gold condition in input.conditions, or -1 for no_match
target.label_null     int    like label, but no_match -> k (virtual "none of them" slot)
target.has_match      0|1
weight                float  training weight (train only; 1.0 for val/test)
meta.*                analysis only -- MUST NOT be fed to a model
meta.gold_seen_exact  true only if the very same condition (same id/description source) was a gold in train; slice `cond:seen`
                      also contains conditions seen only as an EQUIVALENT (same meaning, different service/wording)
```

Rules: never feed `meta`; never tune on `test`; report main examples (`meta.is_paired == false`) and SGD-X paraphrase pairs
(`meta.is_paired == true`) separately; report metrics per `meta.slices`, not only in aggregate.
"""

_WS = re.compile(r"\s+")
_CTRL = re.compile("[\u200b-\u200f\u2028\u2029\ufeff\x00-\x08\x0b\x0c\x0e-\x1f]")
ROLE_NAME = {"user": "User", "assistant": "Assistant"}


@dataclass(frozen=True)
class ModelDataConfig:
    max_context_turns: int = 6
    max_context_words: int = 160  # budget exceeded -> the OLDEST turns are dropped
    max_message_words: int = 200  # the message is only cut when it is absurdly long
    max_condition_words: int = 64
    include_node: bool = True  # False => node text is left out of the query (ablation)
    dataset_weight_power: float = 0.5  # train weight ~ n_dataset^(-p); 0 = raw distribution, 1 = fully balanced
    risky_label_weight: float = 0.5  # multiplier for examples whose label_risk != "none"
    max_k: int = 10

    def __post_init__(self) -> None:
        if (
            min(
                self.max_context_turns,
                self.max_context_words,
                self.max_message_words,
                self.max_condition_words,
                self.max_k,
            )
            < 1
        ):
            raise ValueError("limits must be >= 1")
        if self.dataset_weight_power < 0 or not 0 < self.risky_label_weight <= 1:
            raise ValueError("dataset_weight_power must be >= 0 and risky_label_weight in (0, 1]")


class Preprocessor:
    """Stateless text policy plus counters of what it changed (reported in the manifest)."""

    def __init__(self, cfg: ModelDataConfig):
        self.cfg = cfg
        self.stats: Counter = Counter()

    def norm(self, text: str) -> str:
        out = _WS.sub(" ", _CTRL.sub("", unicodedata.normalize("NFC", text))).strip()
        if out != text:
            self.stats["text_changed_by_normalization"] += 1
        return out

    def _cap(self, text: str, n: int, keep: str, counter: str) -> str:
        words = text.split()
        if len(words) <= n:
            return text
        self.stats[counter] += 1
        return " ".join(words[:n] if keep == "head" else words[-n:])

    def context(self, turns: list[dict]) -> list[dict]:
        turns = [{"role": t["role"], "content": self.norm(t["content"])} for t in turns]
        turns = [t for t in turns if t["content"]][-self.cfg.max_context_turns :]
        kept: list[dict] = []
        budget = self.cfg.max_context_words
        for t in reversed(turns):
            n = len(t["content"].split())
            if n <= budget:
                kept.append(t)
                budget -= n
                continue
            if not kept and budget > 0:  # the newest turn alone exceeds the budget -> keep its tail
                kept.append(
                    {
                        "role": t["role"],
                        "content": self._cap(t["content"], budget, "tail", "newest_context_turn_truncated"),
                    }
                )
            break
        kept.reverse()
        if len(kept) < len(turns):
            self.stats["context_turns_dropped_examples"] += 1
        return kept

    def query(self, node: dict, context: list[dict], message: str) -> str:
        parts = []
        if self.cfg.include_node:
            parts.append(f"Workflow node: {node['name'].replace('_', ' ')}. {self.norm(node['description'])}")
        if context:
            parts.append(
                "Conversation so far:\n" + "\n".join(f"{ROLE_NAME[t['role']]}: {t['content']}" for t in context)
            )
        parts.append(f"Current user message: {message}")
        return "\n".join(parts)

    def record(self, raw: dict, weight: float, train_gold_uids: set[str]) -> dict:
        cfg = self.cfg
        ctx = self.context(raw["context"])
        msg = self._cap(self.norm(raw["current_message"]), cfg.max_message_words, "head", "message_truncated")
        conds = [
            self._cap(self.norm(c["description"]), cfg.max_condition_words, "head", "condition_truncated")
            for c in raw["candidates"]
        ]
        cids = [c["cid"] for c in raw["candidates"]]
        meta = raw["candidate_meta"]
        k = len(conds)
        if not msg or not all(conds) or len(set(conds)) != k or not 2 <= k <= cfg.max_k:
            raise PipelineError(
                f"{raw['example_id']}: empty/duplicate text or candidate count outside [2, {cfg.max_k}]"
            )
        label = cids.index(raw["gold_cid"]) if raw["gold_cid"] is not None else -1
        gold_uid = meta[label]["condition_uid"] if label >= 0 else None
        c = raw["construction"]
        return {
            "example_id": raw["example_id"],
            "split": raw["split"],
            "input": {
                "node": {"name": raw["node"]["name"], "description": self.norm(raw["node"]["description"])},
                "context": ctx,
                "message": msg,
                "query": self.query(raw["node"], ctx, msg),
                "conditions": conds,
            },
            "target": {"label": label, "label_null": label if label >= 0 else k, "has_match": int(label >= 0)},
            "weight": round(weight, 6),
            "meta": {  # never fed to a model: error analysis and slice reporting only
                "dataset": raw["source"]["dataset"],
                "tier": raw["tier"],
                "label_type": raw["label_type"],
                "nm_kind": c["kind"] if raw["label_type"] == "no_match" else None,
                "label_risk": c["label_risk"],
                "n_candidates": k,
                "is_paired": c["paired_with"] is not None,
                "paired_with": c["paired_with"],
                "description_variant": c["description_variant"],
                "slices": raw["slices"],
                "cids": cids,
                "condition_uids": [m["condition_uid"] for m in meta],
                "families": [m["family"] for m in meta],
                "dialogue_id": raw["source"]["dialogue_id"],
                "gold_seen_exact": (gold_uid in train_gold_uids) if gold_uid else None,
            },
        }


def _iter_jsonl(path: Path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            yield json.loads(line)


def dataset_weights(counts: Counter, cfg: ModelDataConfig) -> dict[str, float]:
    """Per-dataset training weights, normalised so the mean over train main examples is exactly 1.

    ``counts`` maps ``(dataset, risky)`` -> number of train main examples.
    """
    n_ds: Counter = Counter()
    for (ds, _), n in counts.items():
        n_ds[ds] += n
    raw = {ds: n ** (-cfg.dataset_weight_power) for ds, n in n_ds.items()}
    total = sum(n_ds.values())
    mean = sum(raw[ds] * (n * (cfg.risky_label_weight if risky else 1.0)) for (ds, risky), n in counts.items()) / total
    return {ds: w / mean for ds, w in raw.items()}


def export(src: Path, out: Path, cfg: ModelDataConfig | None = None, log=print) -> dict:
    cfg = cfg or ModelDataConfig()
    manifest_path = src / "manifest.json"
    if not manifest_path.exists():
        raise PipelineError(f"{manifest_path} not found: build the benchmark first (pathwiser benchmark build)")
    src_manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    for name in SOURCE_JSONL:
        if sha256_file(src / name) != src_manifest["files"][name]["sha256"]:
            raise PipelineError(
                f"{name}: checksum differs from the benchmark manifest (dataset changed since the build)"
            )
    log(f"source verified: {src} (version {src_manifest['version']})")

    # pass 1 (train only): weights and the set of conditions seen as gold during training
    counts: Counter = Counter()
    train_gold: set[str] = set()
    for raw in _iter_jsonl(src / "train.jsonl"):
        if raw["construction"]["paired_with"] is None:
            counts[(raw["source"]["dataset"], raw["construction"]["label_risk"] != "none")] += 1
        if raw["gold_cid"] is not None:
            train_gold.add(next(m["condition_uid"] for m in raw["candidate_meta"] if m["role"] == "gold"))
    ds_weight = dataset_weights(counts, cfg)

    # pass 2: transform and write (into a temporary directory that replaces `out` only on success)
    pre = Preprocessor(cfg)
    tmp = out.parent / (out.name + ".tmp")
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    files: dict[str, dict] = {}
    for split in SPLITS:
        h, n, prev = hashlib.sha256(), 0, ""
        with open(tmp / f"{split}.jsonl", "wb") as f:
            for raw in _iter_jsonl(src / f"{split}.jsonl"):
                if raw["example_id"] <= prev or raw["split"] != split:
                    raise PipelineError(f"{split}.jsonl: examples must be sorted by id and belong to the split")
                prev = raw["example_id"]
                risky = raw["construction"]["label_risk"] != "none"
                weight = (
                    ds_weight[raw["source"]["dataset"]] * (cfg.risky_label_weight if risky else 1.0)
                    if split == "train"
                    else 1.0
                )
                line = (
                    json.dumps(
                        pre.record(raw, weight, train_gold), ensure_ascii=False, sort_keys=True, separators=(",", ":")
                    )
                    + "\n"
                ).encode("utf-8")
                f.write(line)
                h.update(line)
                n += 1
        files[f"{split}.jsonl"] = {"rows": n, "sha256": h.hexdigest()}
        log(f"  {split}: {n:,} examples")
    files["SCHEMA.md"] = {"sha256": write_text(tmp / "SCHEMA.md", SCHEMA_MD)}
    manifest = {
        "version": f"{src_manifest['version']}-model",
        "source_version": src_manifest["version"],
        "source_files_sha256": {n: src_manifest["files"][n]["sha256"] for n in SOURCE_JSONL},
        "preprocessing": asdict(cfg),
        "dataset_weights": {d: round(w, 6) for d, w in sorted(ds_weight.items())},
        "stats": dict(pre.stats),
        "files": files,
    }
    (tmp / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8", newline="\n")
    if out.exists():
        shutil.rmtree(out)
    tmp.rename(out)
    log(f"wrote {out}")
    return manifest


def main(argv: list[str] | None = None, prog: str | None = None) -> int:
    p = argparse.ArgumentParser(
        prog=prog, description="Turn the validated benchmark into model-ready listwise records."
    )
    d = ModelDataConfig()
    p.add_argument("--src", default="data/processed/v1", help="benchmark directory (default: %(default)s)")
    p.add_argument("--out", default="data/model/v1", help="output directory (default: %(default)s)")
    p.add_argument("--no-node", action="store_true", help="leave the workflow node out of the query (ablation)")
    p.add_argument("--max-context-words", type=int, default=d.max_context_words)
    p.add_argument("--dataset-weight-power", type=float, default=d.dataset_weight_power)
    p.add_argument("--risky-label-weight", type=float, default=d.risky_label_weight)
    a = p.parse_args(argv)
    try:
        cfg = ModelDataConfig(
            include_node=not a.no_node,
            max_context_words=a.max_context_words,
            dataset_weight_power=a.dataset_weight_power,
            risky_label_weight=a.risky_label_weight,
        )
        export(Path(a.src).resolve(), Path(a.out).resolve(), cfg, log=lambda s: print(s, file=sys.stderr, flush=True))
    except (PipelineError, ValueError) as e:
        print(f"\nFAILED: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
